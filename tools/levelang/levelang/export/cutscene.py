"""Level IR -> Cutscene.cs: the scene() timeline as functions of time, for the game to play (print) before the level starts.

Everything is `if` chains over time, latest event first (no arrays, no switch: the C build's subset). `Cutscene.ActorX(a, t)` etc. give the
same numbers as the preview GIF (same easings), so what the GIF shows is what the game plays.
"""
from __future__ import annotations

from ..runtime import Level
from ..scene import Scene

EASE_CODE = {"linear": 0, "in": 1, "out": 2, "inout": 3, "cut": 4}


def _f(v: float) -> str:
    return f"{v:.6g}f"


def _cs(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def _text(c: dict) -> str:
    if c["kind"] == "title":
        return f"== {c['text']}" + (f": {c['sub']}" if c.get("sub") else "") + " =="
    return (f"{c['who']}: " if c.get("who") else "") + c["text"]


def _picker(out, name, ret, actors, body):
    """`static <ret> name(int a, float t)` with one `if (a == i)` block per actor; `body(actor)` gives its lines (or None)."""
    out.append(f"    public static {ret} {name}(int a, float t)")
    out.append("    {")
    for i, actor in enumerate(actors):
        lines, default = body(actor)
        out.append(f"        if (a == {i})")
        out.append("        {")
        out += ["            " + l for l in lines]
        out.append(f"            return {default};")
        out.append("        }")
    out.append("        return " + ("0f" if ret == "float" else '""' if ret == "string" else "false") + ";")
    out.append("    }")
    out.append("")


def to_cutscene_cs(level: Level, source: str = "intro.lvl") -> str:
    sc: Scene | None = level.scene
    if sc is None:
        raise ValueError("the level has no scene(): nothing to export")
    actors = list(sc.actors.values())
    caps = sorted(sc.captions, key=lambda c: c["t"])
    emotes = sorted(((t, a.name, tile.name.removeprefix("tile_").lower().replace("_", " "), s) for a in actors for t, tile, s in a.emotes))
    out = [f"// GENERATED by levelang from {source}: edit that file, not this one", "static class Cutscene", "{",
           f"    public const float Seconds = {_f(sc.seconds)};", f"    public const int ActorCount = {len(actors)};", f"    public const int Count = {len(caps)};",
           f"    public const int EmoteCount = {len(emotes)};", ""]
    out += ["    // 0 linear, 1 in, 2 out, 3 in-out, 4 cut (jumps at the end time)",
            "    public static float Ease(float u, int k)", "    {",
            "        if (u < 0f) u = 0f;", "        if (u > 1f) u = 1f;",
            "        if (k == 1) return u * u;", "        if (k == 2) return 1f - (1f - u) * (1f - u);", "        if (k == 3) return u * u * (3f - 2f * u);",
            "        if (k == 4) { if (u < 1f) return 0f; return 1f; }",
            "        return u;", "    }", "",
            "    public static float Seg(float t0, float t1, float a, float b, float t, int k)", "    {",
            "        return a + (b - a) * Ease((t - t0) / (t1 - t0), k);", "    }", "",
            "    // how high a hop is above the straight line at time t (cells)",
            "    public static float Hop(float t0, float t1, float t, int k, float h)", "    {",
            "        float u = Ease((t - t0) / (t1 - t0), k);", "        return h * 4f * u * (1f - u);", "    }", ""]
    out.append("    public static string ActorName(int a)")
    out.append("    {")
    for i, a in enumerate(actors):
        out.append(f"        if (a == {i}) return {_cs(a.name)};")
    out += ['        return "";', "    }", ""]

    def axis(which):
        def body(a):
            lines = []
            for m in reversed(a.moves):
                if m.ease == "cut":
                    lines.append(f"if (t >= {_f(m.t0)}) return {_f(m.x1 if which == 'x' else m.y1)};")
                    continue
                x1, y1 = (m.x1, m.y1)
                lines.append(f"if (t >= {_f(m.t1)}) return {_f(x1 if which == 'x' else y1)};")
                if which == "x":
                    lines.append(f"if (t >= {_f(m.t0)}) return Seg({_f(m.t0)}, {_f(m.t1)}, {_f(m.x0)}, {_f(m.x1)}, t, {EASE_CODE[m.ease]});")
                else:
                    hop = f" - Hop({_f(m.t0)}, {_f(m.t1)}, t, {EASE_CODE[m.ease]}, {_f(m.hop)})" if m.hop else ""
                    lines.append(f"if (t >= {_f(m.t0)}) return Seg({_f(m.t0)}, {_f(m.t1)}, {_f(m.y0)}, {_f(m.y1)}, t, {EASE_CODE[m.ease]}){hop};")
            return lines, _f(a.x if which == "x" else a.y)
        return body

    out.append("    // the top left corner of the actor's picture, in cells of the stage")
    _picker(out, "ActorX", "float", actors, axis("x"))
    _picker(out, "ActorY", "float", actors, axis("y"))

    def pose_body(a):
        first = "idle" if "idle" in a.poses else next(iter(a.poses))
        return [f"if (t >= {_f(pt)}) return {_cs(name)};" for pt, name in reversed(a.pose_cues)], _cs(first)

    _picker(out, "Pose", "string", actors, pose_body)

    def flip_body(a):
        lines = [f"if (t >= {_f(et)}) return {'true' if f else 'false'};" for et, f in reversed(a.flip_events())]
        return lines, "true" if a.flip else "false"

    def vis_body(a):
        return [f"if (t >= {_f(vt)}) return {'true' if v else 'false'};" for vt, v in reversed(a.vis)], "true"

    out.append("    // true if the actor's picture is mirrored (it looks where it last walked)")
    _picker(out, "Flip", "bool", actors, flip_body)
    out.append("    // false while an actor is not on stage (hide / show)")
    _picker(out, "Visible", "bool", actors, vis_body)

    for name, idx in (("CamBaseX", 1), ("CamBaseY", 2), ("CamBaseZoom", 3)):
        cams = sc.cams
        out.append(f"    public static float {name}(float t)")
        out.append("    {")
        if not cams:
            out.append(f"        return {_f({'CamBaseX': sc.view[0] / 2, 'CamBaseY': sc.view[1] / 2, 'CamBaseZoom': 1.0}[name])};")
        else:
            out.append(f"        if (t >= {_f(cams[-1][0])}) return {_f(cams[-1][idx])};")
            for a, b in reversed(list(zip(cams, cams[1:]))):
                out.append(f"        if (t >= {_f(a[0])}) return Seg({_f(a[0])}, {_f(b[0])}, {_f(a[idx])}, {_f(b[idx])}, t, {EASE_CODE[b[4]]});")
            out.append(f"        return {_f(cams[0][idx])};")
        out += ["    }", ""]

    out += ["    // a triangle wave, -1..1, one period per unit: the shake", "    public static float Tri(float v)", "    {", "        float f = v - (int)v;", "        if (f < 0f) f = f + 1f;",
            "        if (f < 0.5f) return f * 4f - 1f;", "        return 3f - f * 4f;", "    }", ""]
    out += ["    // the zoom of the beat punches: a multiplier, 1 = none", "    public static float Punch(float t)", "    {", "        float m = 1f;", "        float u = 0f;"]
    for p0, amt, dur in sc.punches:
        out.append(f"        if (t >= {_f(p0)} && t < {_f(p0 + dur)}) {{ u = (t - {_f(p0)}) / {_f(dur)}; m = m + {_f(amt)} * (1f - u) * (1f - u); }}")
    out += ["        return m;", "    }", ""]
    for axis_name, tri_arg in (("X", "t * 23f"), ("Y", "t * 31f + 0.3f")):
        out += [f"    public static float Shake{axis_name}(float t)", "    {", "        float s = 0f;"]
        for t0, t1, amp in sc.shakes:
            out.append(f"        if (t >= {_f(t0)} && t < {_f(t1)}) s = s + {_f(amp)} * Tri({tri_arg});")
        out += ["        return s;", "    }", ""]
    out += ["    // the camera centre (cells) and zoom at t: the keys, shaken and punched",
            "    public static float CamX(float t) { return CamBaseX(t) + ShakeX(t); }", "    public static float CamY(float t) { return CamBaseY(t) + ShakeY(t); }",
            "    public static float CamZoom(float t) { return CamBaseZoom(t) * Punch(t); }", ""]

    fades = sorted(sc.fades)
    out.append("    // 0 clear .. 1 covered by FadeColor")
    out += ["    public static float Fade(float t)", "    {"]
    for t0, t1, a0, a1, _ in reversed(fades):
        out.append(f"        if (t >= {_f(t0)}) return Seg({_f(t0)}, {_f(max(t1, t0 + 1e-6))}, {_f(a0)}, {_f(a1)}, t, 0);")
    out += ["        return 0f;", "    }", ""]
    out += ["    public static string FadeColor(float t)", "    {"]
    for t0, _, _, _, c in reversed(fades):
        out.append(f"        if (t >= {_f(t0)}) return {_cs(c)};")
    out += ['        return "black";', "    }", ""]

    out.append("    // the words: line i starts at TextAt(i) and stays for TextFor(i) seconds")
    for fn, ret, fmt in (("TextAt", "float", lambda c: _f(c["t"])), ("TextFor", "float", lambda c: _f(c["seconds"])), ("Text", "string", lambda c: _cs(_text(c)))):
        out += [f"    public static {ret} {fn}(int i)", "    {"]
        for i, c in enumerate(caps):
            out.append(f"        if (i == {i}) return {fmt(c)};")
        out += ["        return " + ("0f" if ret == "float" else '""') + ";", "    }", ""]

    out.append("    // a picture that floats up over an actor's head")
    for fn, ret, fmt in (("EmoteAt", "float", lambda e: _f(e[0])), ("EmoteActor", "string", lambda e: _cs(e[1])), ("EmoteName", "string", lambda e: _cs(e[2]))):
        out += [f"    public static {ret} {fn}(int i)", "    {"]
        for i, e in enumerate(emotes):
            out.append(f"        if (i == {i}) return {fmt(e)};")
        out += ["        return " + ("0f" if ret == "float" else '""') + ";", "    }", ""]
    out[-1:] = []
    out.append("}")
    return "\n".join(out) + "\n"
