"""Level IR -> Story.cs: the say() / title() lines of a level, for the game to print as the player gets to them."""
from __future__ import annotations

from ..runtime import Level


def _cs(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", " ") + '"'


def to_story_cs(level: Level, source: str = "level.lvl") -> str:
    """Lines are sorted by column. `Story.Text(i)` is `Who: text` (or `== title: sub ==` for a chapter card); `if` chains, not arrays or switch: the C build's subset."""
    caps = sorted(level.captions, key=lambda c: c["x"])
    out = [f"// GENERATED by levelang from {source}: edit that file, not this one", "static class Story", "{", f"    public const int Count = {len(caps)};", ""]
    out.append("    // the column of the level where line i begins")
    out.append("    public static float X(int i)")
    out.append("    {")
    for i, c in enumerate(caps):
        out.append(f"        if (i == {i}) return {c['x']:g}f;")
    out.append("        return 0f;")
    out.append("    }")
    out.append("")
    out.append("    public static string Text(int i)")
    out.append("    {")
    for i, c in enumerate(caps):
        if c["kind"] == "title":
            text = f"== {c['text']}" + (f": {c['sub']}" if c.get("sub") else "") + " =="
        else:
            text = (f"{c['who']}: " if c.get("who") else "") + c["text"]
        out.append(f"        if (i == {i}) return {_cs(text)};")
    out.append('        return "";')
    out.append("    }")
    out.append("}")
    return "\n".join(out) + "\n"
